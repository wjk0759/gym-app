from __future__ import annotations

import json
import logging
from functools import lru_cache

from ..config import settings

logger = logging.getLogger(__name__)


class SmsDeliveryError(RuntimeError):
    """Raised when the upstream SMS provider rejects or fails a send."""


def _mask_phone(phone: str) -> str:
    if len(phone) < 7:
        return "***"
    return f"{phone[:3]}****{phone[-4:]}"


@lru_cache(maxsize=1)
def _aliyun_client():
    from alibabacloud_dypnsapi20170525.client import Client
    from alibabacloud_tea_openapi import models as open_api_models

    config = open_api_models.Config(
        access_key_id=settings.aliyun_pnvs_access_key_id,
        access_key_secret=settings.aliyun_pnvs_access_key_secret,
    )
    config.endpoint = settings.aliyun_pnvs_endpoint
    return Client(config)


def _require_config() -> None:
    missing = [
        name
        for name, value in (
            ("ALIYUN_PNVS_ACCESS_KEY_ID", settings.aliyun_pnvs_access_key_id),
            (
                "ALIYUN_PNVS_ACCESS_KEY_SECRET",
                settings.aliyun_pnvs_access_key_secret,
            ),
            ("ALIYUN_PNVS_SIGN_NAME", settings.aliyun_pnvs_sign_name),
            ("ALIYUN_PNVS_TEMPLATE_CODE", settings.aliyun_pnvs_template_code),
        )
        if not value.strip()
    ]
    if missing:
        raise SmsDeliveryError("阿里云短信认证配置不完整：" + ", ".join(missing))


def send_aliyun_pnvs_code(phone: str, code: str) -> None:
    """Send a verification code through Alibaba Cloud PNVS SMS authentication.

    The code is generated by the application and stored as a hash in our own
    database. PNVS only delivers the message; verification stays in our
    existing ``sms_codes`` flow.
    """
    _require_config()

    from alibabacloud_dypnsapi20170525 import models
    from alibabacloud_tea_util import models as util_models

    request = models.SendSmsVerifyCodeRequest(
        phone_number=phone,
        sign_name=settings.aliyun_pnvs_sign_name,
        template_code=settings.aliyun_pnvs_template_code,
        template_param=json.dumps({"code": code, "min": "5"}, ensure_ascii=False),
        code_length=6,
        valid_time=300,
        interval=60,
        country_code=settings.aliyun_pnvs_country_code,
        return_verify_code=False,
    )
    try:
        response = _aliyun_client().send_sms_verify_code_with_options(
            request, util_models.RuntimeOptions()
        )
    except Exception as exc:  # SDK raises TeaException and transport errors
        logger.exception("aliyun_pnvs_send_failed phone=%s", _mask_phone(phone))
        raise SmsDeliveryError("阿里云短信认证发送失败") from exc

    body = getattr(response, "body", None)
    result_code = getattr(body, "code", None)
    if result_code != "OK":
        message = getattr(body, "message", "")
        logger.warning(
            "aliyun_pnvs_rejected phone=%s code=%s message=%s",
            _mask_phone(phone),
            result_code,
            message,
        )
        raise SmsDeliveryError(
            f"阿里云短信认证发送失败：{result_code} {message}".strip()
        )
