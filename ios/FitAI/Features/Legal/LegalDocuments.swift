// MARK: - Legal documents

enum LegalDocumentKind: String, Identifiable, CaseIterable {
    case terms
    case privacy
    case health
    case ai

    var id: String { rawValue }

    var title: String {
        switch self {
        case .terms: return "用户协议"
        case .privacy: return "隐私政策"
        case .health: return "健康免责声明"
        case .ai: return "生成式 AI 服务说明"
        }
    }

    var document: LegalDocument {
        switch self {
        case .terms: return LegalDocuments.terms
        case .privacy: return LegalDocuments.privacy
        case .health: return LegalDocuments.health
        case .ai: return LegalDocuments.ai
        }
    }
}

